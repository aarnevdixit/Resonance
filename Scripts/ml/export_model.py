"""
Fit the chosen model on ALL Minsk2020 speakers and export it as a Swift source file.

Usage: python3 export_model.py "<model name>" "<training set>"
  e.g. python3 export_model.py "Logistic regression" "/a/ + /i/"

The hyperparameters are chosen by the same grouped 5-fold grid search used inside the
nested cross-validation. The reported accuracy comes from train.py (held-out speakers),
never from this final fit.

Output: SpeechChangeModelWeights.swift, plain Swift arrays read by SpeechChangeModel.swift.
"""
import json, sys
import numpy as np
from sklearn.base import clone
from sklearn.model_selection import GridSearchCV, StratifiedGroupKFold
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from features import FEATURE_NAMES
from train import MODELS, RNG, df

name, tag = sys.argv[1], sys.argv[2]
vowels = ["a"] if tag == "/a/ only" else ["a", "i"]
model, grid = MODELS[name]
tr = df[df.vowel.isin(vowels)]
X, y, g = tr[FEATURE_NAMES].values.astype(float), tr.label.values, tr.speaker.values
pipe = Pipeline([("scale", StandardScaler()), ("clf", clone(model))])
search = GridSearchCV(pipe, grid, scoring="roc_auc",
                      cv=StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=RNG), n_jobs=2)
search.fit(X, y, groups=g)
best = search.best_estimator_
scaler, clf = best.named_steps["scale"], best.named_steps["clf"]
print("best params:", search.best_params_, "inner AUC:", round(search.best_score_, 3))


def arr(v, fmt="{:.10g}"):
    return "[" + ", ".join(fmt.format(float(x)) for x in np.ravel(v)) + "]"


def tree_swift(t):
    tr_ = t.tree_
    vals = tr_.value[:, 0, :]
    if vals.shape[1] == 2:  # classifier: proportion of class 1
        vals = vals[:, 1] / np.maximum(vals.sum(axis=1), 1e-12)
    else:  # regressor (gradient boosting stage)
        vals = vals[:, 0]
    return ("Tree(feature: " + arr(tr_.feature, "{:.0f}") +
            ", threshold: " + arr(tr_.threshold) +
            ", left: " + arr(tr_.children_left, "{:.0f}") +
            ", right: " + arr(tr_.children_right, "{:.0f}") +
            ", value: " + arr(vals) + ")")


lines = [
    "//",
    "//  SpeechChangeModelWeights.swift",
    "//  Resonance",
    "//",
    "//  GENERATED by Scripts/ml/export_model.py. Do not edit by hand.",
    f"//  Model: {name}, trained on {tag} recordings from all 64 Minsk2020 speakers.",
    f"//  Settings: {json.dumps({k: str(v) for k, v in search.best_params_.items()})}",
    "//",
    "",
    "import Foundation",
    "",
    "extension SpeechChangeModel {",
    f"    static let modelName = \"{name}\"",
    f"    static let scalerMean: [Double] = {arr(scaler.mean_)}",
    f"    static let scalerScale: [Double] = {arr(scaler.scale_)}",
]

kind = type(clf).__name__
if kind in ("LogisticRegression", "LinearDiscriminantAnalysis"):
    lines += ["    static let kind = Kind.linear(",
              f"        coef: {arr(clf.coef_)},",
              f"        intercept: {float(np.ravel(clf.intercept_)[0]):.10g})"]
elif kind == "SVC":
    gamma = clf._gamma
    sv = ",\n            ".join(arr(r) for r in clf.support_vectors_)
    lines += ["    static let kind = Kind.rbfSVM(",
              f"        supportVectors: [\n            {sv}],",
              f"        dualCoef: {arr(clf.dual_coef_)},",
              f"        intercept: {float(clf.intercept_[0]):.10g},",
              f"        gamma: {gamma:.10g})"]
elif kind == "RandomForestClassifier":
    trees = ",\n        ".join(tree_swift(t) for t in clf.estimators_)
    lines += [f"    static let kind = Kind.forest(trees: [\n        {trees}])"]
elif kind == "GradientBoostingClassifier":
    prior = clf.init_.class_prior_[1]
    init = float(np.log(prior / (1 - prior)))
    trees = ",\n        ".join(tree_swift(t) for t in clf.estimators_[:, 0])
    lines += [f"    static let kind = Kind.boosting(initial: {init:.10g}, learningRate: {clf.learning_rate:.10g}, trees: [\n        {trees}])"]
else:
    raise SystemExit(f"Export not supported for {kind}")

lines += ["}", ""]
open("SpeechChangeModelWeights.swift", "w").write("\n".join(lines))

# Reference outputs for the Swift unit test: first 3 /a/ recordings.
a = df[df.vowel == "a"].head(3)
ref = best.predict_proba(a[FEATURE_NAMES].values.astype(float))[:, 1] if hasattr(best, "predict_proba") \
    else 1 / (1 + np.exp(-best.decision_function(a[FEATURE_NAMES].values.astype(float))))
json.dump({"features": a[FEATURE_NAMES].values.tolist(), "probability": ref.tolist()},
          open("model_reference.json", "w"), indent=1)
print("wrote SpeechChangeModelWeights.swift and model_reference.json")
