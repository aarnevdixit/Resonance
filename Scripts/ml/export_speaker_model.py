"""
Fit the chosen two-vowel model on ALL speakers and export it as Swift.

Usage: python3 export_speaker_model.py <LDA|LR|SVM> <feature set name>
Feature sets are the ones defined in exp_speaker.py. Reads speaker_table.csv (written by it).
The accuracy we report comes from exp_speaker.py (held-out speakers), never from this fit.
"""
import json, sys
import numpy as np, pandas as pd
from sklearn.discriminant_analysis import LinearDiscriminantAnalysis
from sklearn.feature_selection import SelectKBest, f_classif
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GridSearchCV, StratifiedKFold
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from features import FEATURE_NAMES

A10 = [c + "_a" for c in FEATURE_NAMES]; I10 = [c + "_i" for c in FEATURE_NAMES]
FORM = ["F1_a", "F2_a", "F1_i", "F2_i", "F2ratio", "vowelSpace"]
SETS = {"a10": A10, "a10+i10": A10 + I10, "formants": FORM, "a10+formants": A10 + FORM,
        "a10+i10+formants": A10 + I10 + FORM,
        "F2_i+vowelSpace+5best": ["F2_i", "vowelSpace", "F2ratio", "voicedRatio_a", "f0StdSemi_a", "jitter_a", "cpp_a"]}
MODELS = {"LDA": (LinearDiscriminantAnalysis(solver="lsqr"), {"clf__shrinkage": [0.2, 0.5, 0.8, "auto"]}),
          "LR": (LogisticRegression(max_iter=5000), {"clf__C": [0.01, 0.03, 0.1, 0.3, 1]}),
          "SVM": (SVC(), {"clf__C": [0.3, 1, 3], "clf__gamma": ["scale", 0.03, 0.1]})}

mname, sname = sys.argv[1], sys.argv[2]
cols = SETS[sname]
d = pd.read_csv("speaker_table.csv", index_col=0)
X, y = d[cols].values.astype(float), d.label.values
if mname == "LDA+select":
    # Same as exp_select.py: keep the k most informative features, chosen on training data only.
    pipe = Pipeline([("imp", SimpleImputer(strategy="median")), ("s", StandardScaler()),
                     ("sel", SelectKBest(f_classif)), ("clf", LinearDiscriminantAnalysis(solver="lsqr"))])
    grid = {"sel__k": [4, 6, 8, 10, 12, len(cols)], "clf__shrinkage": [0.2, 0.5, 0.8, "auto"]}
else:
    model, grid = MODELS[mname]
    pipe = Pipeline([("imp", SimpleImputer(strategy="median")), ("s", StandardScaler()), ("clf", model)])
gs = GridSearchCV(pipe, grid, scoring="roc_auc", cv=StratifiedKFold(5, shuffle=True, random_state=7), n_jobs=2)
gs.fit(X, y)
best = gs.best_estimator_
imp, sc, clf = best.named_steps["imp"], best.named_steps["s"], best.named_steps["clf"]
mask = best.named_steps["sel"].get_support() if "sel" in best.named_steps else np.ones(len(cols), bool)
all_cols = cols
cols = [c for c, m in zip(cols, mask) if m]
print("selected features:", cols)
print("best params:", gs.best_params_, "inner AUC:", round(gs.best_score_, 3))


def arr(v):
    return "[" + ", ".join(f"{float(x):.10g}" for x in np.ravel(v)) + "]"


lines = ["//", "//  SpeechChangeModelWeights.swift", "//  Resonance", "//",
         "//  GENERATED by Scripts/ml/export_speaker_model.py. Do not edit by hand.",
         f"//  Model: {mname}, features: {sname}, trained on all {len(y)} Minsk2020 speakers",
         "//  (one row per person: their held \"ahh\" and held \"eee\").",
         f"//  Settings: {json.dumps({k: str(v) for k, v in gs.best_params_.items()})}",
         "//", "", "import Foundation", "", "extension SpeechChangeModel {",
         f"    static let modelName = \"{mname} ({sname})\"",
         "    static let featureNames: [String] = [" + ", ".join(f"\"{c}\"" for c in cols) + "]",
         f"    static let imputeMedian: [Double] = {arr(imp.statistics_[mask])}",
         f"    static let scalerMean: [Double] = {arr(sc.mean_[mask])}",
         f"    static let scalerScale: [Double] = {arr(sc.scale_[mask])}"]
kind = type(clf).__name__
if kind in ("LogisticRegression", "LinearDiscriminantAnalysis"):
    lines += ["    static let kind = Kind.linear(", f"        coef: {arr(clf.coef_)},",
              f"        intercept: {float(np.ravel(clf.intercept_)[0]):.10g})"]
elif kind == "SVC":
    sv = ",\n            ".join(arr(r) for r in clf.support_vectors_)
    lines += ["    static let kind = Kind.rbfSVM(", f"        supportVectors: [\n            {sv}],",
              f"        dualCoef: {arr(clf.dual_coef_)},", f"        intercept: {float(clf.intercept_[0]):.10g},",
              f"        gamma: {clf._gamma:.10g})"]
lines += ["}", ""]
open("SpeechChangeModelWeights.swift", "w").write("\n".join(lines))

ref = d.head(3)
Xr = ref[cols].values.astype(float)
Xfull = ref[all_cols].values.astype(float)
p = best.predict_proba(Xfull)[:, 1] if hasattr(best, "predict_proba") else 1 / (1 + np.exp(-best.decision_function(Xfull)))
json.dump({"names": cols, "rows": [[None if np.isnan(v) else v for v in r] for r in Xr.tolist()],
           "probability": p.tolist(),
           "coef_by_feature": dict(zip(cols, np.ravel(getattr(clf, "coef_", np.zeros(len(cols)))).round(3).tolist()))},
          open("model_reference.json", "w"), indent=1)
print("wrote SpeechChangeModelWeights.swift and model_reference.json")
